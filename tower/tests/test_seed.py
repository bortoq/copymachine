"""Tests of the seed (23.7): the encoder of language 1 `programs/seed.tw` is a program of the chain. It reads the text of
language 1 (l1text.py) from stdin and writes the image of the emulator; its image, made from its own text
(`programs/seed.l1`), is itself, byte for byte (the fixed point, as hex0 of stage0). Wrong texts are reported to stderr and
the image is cut at that place. All runs are on the checked emulator.
Run: make check-tower  or  python3 -B tower/tests/test_seed.py"""
import os
import random
import subprocess
import sys

sys.dont_write_bytecode = True
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
import common
import l1text
import text
from common import Mem, run
from test_tower import intervals

PROGRAMS = os.path.join(common.HERE, 'programs')
LIMIT = 20 * 10 ** 6


def setUpModule():
    common.ensure_built()


def source(name):
    with open(os.path.join(PROGRAMS, name + '.tw'), encoding='utf-8') as h:
        return h.read()


def compiled(name):
    p, errs = text.compile_text(source(name))
    assert not errs, errs
    return p


class Reference(unittest.TestCase):
    """The text of an image and the Python reference of the encoder (no emulator)."""

    def test_every_program_to_text_and_back(self):
        """The text made from each program of programs/ gives its image byte for byte."""
        for f in sorted(os.listdir(PROGRAMS)):
            if f.endswith('.tw'):
                with self.subTest(f):
                    p = compiled(f[:-3])
                    img, err = l1text.encode(l1text.program_text(p))
                    self.assertIsNone(err)
                    self.assertEqual(img, p.stats['image'])

    def test_seed_text_is_current(self):
        """seed.l1 is what l1text makes from seed.tw (it is in git: a change of the seed must regenerate it)."""
        p = compiled('seed')
        want = l1text.program_text(p, 'the image of seed.tw (A=%d, P=%d), generated by tower/l1text.py' % (
            p.stats['A'], p.stats['P']))
        with open(os.path.join(PROGRAMS, 'seed.l1'), encoding='utf-8') as h:
            self.assertEqual(h.read(), want)

    def test_cli(self):
        root = os.path.dirname(common.HERE)
        r = subprocess.run([sys.executable, '-B', 'tower/l1text.py', 'tower/programs/echo.tw'], cwd=root, check=False,
                           capture_output=True, timeout=120)
        self.assertEqual(r.returncode, 0, r.stderr)
        e = subprocess.run([sys.executable, '-B', 'tower/l1text.py', '-e'], input=r.stdout, cwd=root, check=False,
                           capture_output=True, timeout=120)
        self.assertEqual((e.returncode, e.stdout), (0, compiled('echo').stats['image']))
        e = subprocess.run([sys.executable, '-B', 'tower/l1text.py', '-e'], input=b'q\n', cwd=root, check=False,
                           capture_output=True, timeout=120)
        self.assertEqual((e.returncode, e.stdout, e.stderr), (1, b'', b'l1: bad text\n'))


class Seed(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.seed = compiled('seed')
        cls.st = cls.seed.stats

    def encoder(self, src):
        """Run the image of the seed with the text on stdin (and the zero byte which ends it)."""
        r = run(self.st['image'], self.st['A'], self.st['P'], checked=True, limit=LIMIT,
                stdin=src if isinstance(src, bytes) else src.encode('latin-1') + b'\0')
        self.assertEqual(r.rc, 0, r.err)
        self.assertLess(r.ticks, LIMIT)
        return r

    def check_text(self, src):
        """The chain and the Python reference agree: the same bytes and the same report."""
        r = self.encoder(src)
        want, err = l1text.encode(src)
        self.assertEqual(r.out, want, src)
        self.assertEqual('l1: ' in r.err, err is not None, (src, r.err))
        if err:
            self.assertIn(l1text.MESSAGES[err], r.err)
        return r

    def test_audit(self):
        intervals(self.seed)

    def test_programs(self):
        """The image the chain makes from the text of a program is the image the Python compiler made."""
        for name in ('add', 'branch', 'calls', 'echo', 'fib', 'array', 'arith8', 'long_cat', 'and_hex'):
            with self.subTest(name):
                p = compiled(name)
                r = self.encoder(l1text.program_text(p))
                self.assertEqual(r.out, p.stats['image'])
                self.assertNotIn('l1: ', r.err)

    def test_fixed_point(self):
        """The seed turns its own text into its own image, byte for byte; that image does it again."""
        with open(os.path.join(PROGRAMS, 'seed.l1'), 'rb') as h:
            own = h.read()
        r = self.encoder(own + b'\0')
        self.assertEqual(r.out, self.st['image'])
        self.assertNotIn('l1: ', r.err)
        self.assertEqual(l1text.encode(own)[0], self.st['image'])
        r2 = run(r.out, self.st['A'], self.st['P'], checked=True, limit=LIMIT, stdin=own + b'\0')
        self.assertEqual(r2.out, self.st['image'])

    def test_add4_is_data(self):
        """The table of the sum is raw bits of the text: the entries of the image made from the text are the sums."""
        with open(os.path.join(PROGRAMS, 'seed.l1'), encoding='utf-8') as h:
            own = h.read()
        self.assertIn('add4 (5-bit entries', own)
        img = l1text.encode(own)[0]
        mem, bo = Mem(), self.st['boot_bytes']
        mem.b = bytearray(img[bo:])
        T = self.seed.tables['add4']
        for a in range(16):
            for b in range(16):
                for c in range(2):
                    idx = a | b << 4 | c << 8
                    self.assertEqual(mem.get(T.data.addr + (idx << T.j), 5), a + b + c)

    def test_small_texts(self):
        """The words of the text: w, r, z, s, comments, blanks and tabs; bits are written in the order of memory."""
        for src in ('w 10\nr 1 2 3 4\n', 'w 8\nr ff 0 1 80\n', 'z 8\n', 's 11110000\n', 's 1 0 1 0 1 0 1 0\n',
                    'w 4\nr 1 2 3 4\n', '# nothing\n\n  \t w 3\n z 3\ns 01\n', 'w 10\nr 1 2 3 4\nz 18\ns 1\nz 6\n',
                    'w 10\nr 1 2 3 4', 'w 10\nr 12345 2 3 4\n', 'w 0\n', 'z 100\n', 'w 100\nz ff\n', '', 'w 5 \n z 3 \n',
                    'w 10\r\nr 1 2 3 4\r\n'):
            with self.subTest(src):
                self.check_text(src)
        r = self.encoder('w 10\nr 1 2 3 4\n')
        self.assertEqual(r.out, bytes([0x80, 0, 0x40, 0, 0xc0, 0, 0x20, 0]))

    def test_rejected(self):
        """A wrong text: nothing but the whole bytes before the error is written, the report is on stderr."""
        for src, err in (('q\n', 'bad'), ('a 1\n', 'bad'), ('1\n', 'bad'), ('w\n', 'cnt'), ('w 1 2\n', 'cnt'),
                         ('w 10\nr 1 2 3\n', 'cnt'), ('w 10\nr 1 2 3 4 5\n', 'cnt'), ('r 1 2 3 4\n', 'bad'),
                         ('w 10\nr 1 2 3 g\n', 'bad'), ('w 10\nr 1 2 3 4 # c\n', 'bad'), ('s 012\n', 'bad'),
                         ('s 1', 'end'), ('s 1\nz 3\n', 'end'), ('w 10\nz 4\ns 1\n', 'end'), ('z\n', 'cnt'),
                         ('z 1 2\n', 'cnt'), ('W 10\n', 'bad'), ('# c\nwx\n', 'bad'), ('s 11111111\nq\n', 'bad')):
            with self.subTest(src):
                r = self.check_text(src)
                self.assertIn(l1text.MESSAGES[err], r.err)
        r = self.check_text('s 11111111\nq\n')
        self.assertEqual(r.out, b'\xff')                 # cut at the error: the whole bytes written before it

    def test_random_texts(self):
        """Random changes of a good text (a character changed, dropped, added): the chain and the reference agree."""
        rnd = random.Random(237)
        base = 'w 6\nr 1 2 3 4\nz 4\ns 0101 1100 0\n# c\nz 3\nw a\nz 8\ns 1\nz 7\n'
        alphabet = 'wrzs# 01abfg\n\tx\r2'
        for _ in range(60):
            t = list(base)
            for _ in range(rnd.randint(1, 3)):
                i = rnd.randrange(len(t))
                kind = rnd.randrange(3)
                if kind == 0:
                    t[i] = rnd.choice(alphabet)
                elif kind == 1:
                    del t[i]
                else:
                    t.insert(i, rnd.choice(alphabet))
            self.check_text(''.join(t))


if __name__ == '__main__':
    unittest.main()
