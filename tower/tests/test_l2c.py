"""Tests of the compiler of language 2 (23.8): `programs/l2c.tw` is a program of the chain. It reads the text of language 2
(c, d, labels, o and the lines of language 1) and writes the text of language 1 and a zero byte, which the seed
(23.7) turns into the image. The images made by the chain are the images of the Python compilers; the compiler is built and rebuilt by the
chain from its own texts (l2c.l1, l2c.l2). The outputs of l2c on the small, the wrong and the spoiled texts are frozen in tower/golden/l2c.jsonl
(test_golden.py). All runs are on the checked emulator.
Run: make check-tower  or  python3 -B tower/tests/test_l2c.py"""
import os
import sys

sys.dont_write_bytecode = True
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
sys.path.insert(0, HERE)
import common
import l1
import l1text
import l2
import tables
import test_golden as g
import text
from common import Alloc, Mem, bytes_value, run
from test_tower import intervals

PROGRAMS = os.path.join(common.HERE, 'programs')
LIMIT = 40 * 10 ** 6
TITLE = 'the image of %s.tw (A=%d, P=%d), generated by tower/l1text.py'


def setUpModule():
    common.ensure_built()


def read(name, mode='r'):
    with open(os.path.join(PROGRAMS, name), mode, encoding=None if 'b' in mode else 'utf-8') as h:
        return h.read()


def compiled(name):
    p, errs = text.compile_text(read(name + '.tw'))
    assert not errs, errs
    return p


def text_of(name):
    p = compiled(name)
    return l1text.program_text(p, TITLE % (name, p.stats['A'], p.stats['P']))


class Reference(unittest.TestCase):
    """The texts and the Python reference (no emulator)."""

    def test_tables_are_current(self):
        """The numbers of the tables cls and attr in l2c.tw are what tables.py makes."""
        src = read('l2c.tw')
        for table in tables.l2_tables():
            self.assertIn(table, src)

    def test_texts_are_current(self):
        """l2c.l1 is what l1text makes from l2c.tw, l2c.l2 is its text of language 2 (both are in git)."""
        self.assertEqual(read('l2c.l1'), text_of('l2c'))
        self.assertEqual(read('l2c.l2'), g.to_l2(read('l2c.l1')))

class Compiler(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.comp = compiled('l2c')
        cls.st = cls.comp.stats

    def l2c(self, src):
        """Run the image of the compiler with the text on stdin (and the zero byte which ends it)."""
        r = run(self.st['image'], self.st['A'], self.st['P'], checked=True, limit=LIMIT,
                stdin=src if isinstance(src, bytes) else src.encode('latin-1') + b'\0')
        self.assertEqual(r.rc, 0, r.err)
        self.assertLess(r.ticks, LIMIT)
        return r

    def test_audit(self):
        intervals(self.comp)

    def test_small_texts(self):
        """A copy and a text with data and a label: the text of language 1 (w 10 is A = 16: a row is 64 bits)."""
        r = self.l2c('c 8 10 20\n')
        self.assertEqual(r.out, b'r 10 18 20 28\n\0')
        r = self.l2c('w 10\nr 1 2 3 4\n:a d 8 5\nc 4 &a+1 &a\n')
        self.assertEqual(r.out, b'w 10\nr 1 2 3 4\ns 10100000\nr 41 45 40 44\n\0')

    def test_programs(self):
        """A program written in language 2 (its copy rows are c lines): the chain gives its text of language 1, the seed gives
        its image, and the image is the image the Python compiler made."""
        seed = compiled('seed').stats
        for name in ('echo', 'add', 'branch', 'calls', 'array'):
            with self.subTest(name):
                p = compiled(name)
                t = l1text.program_text(p)
                two = g.to_l2(t)
                r = self.l2c(two)
                self.assertEqual(r.out, t.encode() + b'\0')
                self.assertNotIn('l2: ', r.err)
                q = run(seed['image'], seed['A'], seed['P'], checked=True, limit=LIMIT, stdin=r.out)
                self.assertEqual(q.out, p.stats['image'])
                self.assertNotIn('l1: ', q.err)

    def test_hello(self):
        """A program of language 2 with labels and data (programs/hello.l2): the image made by the chain is the image made by
        the Python compilers of languages 1 and 2 (layers, rows, data); it runs and prints."""
        A = 10
        S = 2 ** A - 6
        x, y, nl, buf = (l2.Data(n, 8 if n != 'buf' else 24, bytes_value(v)) for n, v in
                         (('x', b'H'), ('y', b'i'), ('nl', b'\n'), ('buf', b'')))
        sa = buf.ref().addr
        layers = [l1.Layer([], entry=True),
                  l1.Layer([l2.copy(8, buf[0:8], x.ref()), l2.copy(8, buf[8:16], y.ref()), l2.copy(8, buf[16:24], nl.ref())]),
                  l1.Layer([l1.row(S + 2, S + 2, sa, lambda: sa() + 24)], to='halt')]
        P = l1.widths(A, layers)
        mem, alloc = Mem(), Alloc(S)
        alloc.take(0, P * 4 * A)
        l2.place(alloc, [x, y, nl, buf])
        l1.place(A, layers, alloc)
        l1.encode(A, layers, alloc, mem, P)
        l2.write(mem, [x, y, nl, buf])
        want, _ = l1.image(A, P, mem)
        seed = compiled('seed').stats
        r = self.l2c(read('hello.l2').encode() + b'\0')
        self.assertNotIn('l2: ', r.err)
        q = run(seed['image'], seed['A'], seed['P'], checked=True, limit=LIMIT, stdin=r.out)
        self.assertEqual(q.out, want)
        e = run(q.out, A, P, checked=True)
        self.assertEqual((e.rc, e.out), (0, b'Hi\n'))


class Chain(unittest.TestCase):
    """The tools build each other, no Python between them: the seed, the compiler of language 2, the seed again."""

    def test_self_build(self):
        l1_text, l2_text = read('l2c.l1', 'rb'), read('l2c.l2', 'rb')
        seed_text = read('seed.l1', 'rb')
        seed_img = l1text.encode(seed_text)[0]                       # the first image of the seed: the reference (hex0)
        seed = compiled('seed').stats
        self.assertEqual(seed_img, seed['image'])
        sd = dict(A=seed['A'], P=seed['P'], checked=True, limit=LIMIT)
        # the seed builds the compiler of language 2 from its text of language 1
        a = run(seed_img, stdin=l1_text + b'\0', **sd)
        self.assertEqual(a.rc, 0, a.err)
        self.assertEqual(a.out, compiled('l2c').stats['image'])
        st = compiled('l2c').stats
        sc = dict(A=st['A'], P=st['P'], checked=True, limit=LIMIT)
        # the compiler, written in language 2, gives its own text of language 1; the seed turns it into the same image
        b = run(a.out, stdin=l2_text + b'\0', **sc)
        self.assertEqual(b.rc, 0, b.err)
        self.assertEqual(b.out, l1_text + b'\0')
        self.assertEqual(run(seed_img, stdin=b.out, **sd).out, a.out)
        # the seed, written in language 2 (the copy rows of seed.l1 are c lines): the text of language 1 is seed.l1
        c = run(a.out, stdin=g.to_l2(seed_text.decode()).encode() + b'\0', **sc)
        self.assertEqual(c.out, seed_text + b'\0')
        self.assertEqual(run(seed_img, stdin=c.out, **sd).out, seed_img)


