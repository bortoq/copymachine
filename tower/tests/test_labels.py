PROGRAMS = os.path.join(common.HERE, 'programs')
LIMIT = 40 * 10 ** 6
TITLE = 'the image of %s.tw (A=%d, P=%d), generated by tower/l1text.py'


def setUpModule():
    common.ensure_built()


def read(name, mode='r'):
    with open(os.path.join(PROGRAMS, name), mode, encoding=None if 'b' in mode else 'utf-8') as h:
        return h.read()


def compiled(name):
    p, errs = text.compile_text(read(name + '.tw'))
    assert not errs, errs
    return p


def twice(src):
    """What the tool reads: the text, a zero byte, the text, a zero byte (`cat t t`)."""
    t = src if isinstance(src, bytes) else src.encode('latin-1')
    return t + b'\0' + t + b'\0'


class Reference(unittest.TestCase):
    """The texts (no emulator)."""

    def test_tables_are_current(self):
        """The numbers of the tables cls and attr in l2l.tw are what tables.py makes."""
        src = read('l2l.tw')
        for table in tables.l2l_tables():
            self.assertIn(table, src)

    def test_texts_are_current(self):
        """l2l.l1 is what l1text makes from l2l.tw, l2l.l2 is its text of language 2 (both are in git)."""
        p = compiled('l2l')
        self.assertEqual(read('l2l.l1'), l1text.program_text(p, TITLE % ('l2l', p.stats['A'], p.stats['P'])))
        self.assertEqual(read('l2l.l2'), g.to_l2(read('l2l.l1')))

    def test_capacity_in_the_texts(self):
        """The places of names: 1024 labels in l2l.tw (six arrays of 2^10); the 1024th label fits and the 1025th is `bad label` (frozen: l2l.jsonl, labels-1024, labels-1025)."""
        for n in ('nameh', 'namet', 'tags', 'vals', 'hd', 'nx'):
            self.assertIn(':%s array 10 ' % n, read('l2l.tw'))        # 2^10 = tables.MAXLAB


class Tool(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.comp = compiled('l2l')
        cls.st = cls.comp.stats

    def l2l(self, stdin, limit=LIMIT):
        r = run(self.st['image'], self.st['A'], self.st['P'], checked=True, limit=limit, stdin=stdin)
        self.assertEqual(r.rc, 0, r.err)
        self.assertLess(r.ticks, limit)
        return r

    def test_audit(self):
        intervals(self.comp)

    def test_hello_names(self):
        """hello_names.l2 (names, a reference forward): the seed turns the text of language 1 of l2l into the image of the Python compilers of hello.l2
        (its test is in test_l2c) and the image runs and prints."""
        r = self.l2l(twice(read('hello_names.l2').encode()))
        self.assertNotIn('l2l: ', r.err)
        seed = compiled('seed').stats
        q = run(seed['image'], seed['A'], seed['P'], checked=True, limit=LIMIT, stdin=r.out)
        self.assertNotIn('l1: ', q.err)
        e = run(q.out, 10, 4, checked=True)
        self.assertEqual((e.rc, e.out), (0, b'Hi\n'))
        # the same program through l2c (one-letter names) is the same image
        c = compiled('l2c').stats
        via = run(c['image'], c['A'], c['P'], checked=True, limit=LIMIT, stdin=read('hello.l2', 'rb') + b'\0')
        self.assertEqual(run(seed['image'], seed['A'], seed['P'], checked=True, limit=LIMIT, stdin=via.out).out, q.out)


class Chain(unittest.TestCase):
    """The tools build each other, no Python between them: the seed, the compiler of language 2, the label tool."""

    def test_self_build(self):
        l1_text, l2_text = read('l2l.l1', 'rb'), read('l2l.l2', 'rb')
        seed_img = l1text.encode(read('seed.l1', 'rb'))[0]
        seed, st, l2c = compiled('seed').stats, compiled('l2l').stats, compiled('l2c').stats
        sd = dict(A=seed['A'], P=seed['P'], checked=True, limit=LIMIT)
        # the seed builds the label tool from its text of language 1
        a = run(seed_img, stdin=l1_text + b'\0', **sd)
        self.assertEqual(a.rc, 0, a.err)
        self.assertEqual(a.out, st['image'])
        # l2c (23.8) builds the text of language 1 of the label tool from its text of language 2 (the tool needs no label, its
        # numbers are the numbers of l1text): the older tool builds the newer one
        b = run(l2c['image'], l2c['A'], l2c['P'], checked=True, limit=LIMIT, stdin=l2_text + b'\0')
        self.assertEqual(b.out, l1_text + b'\0')
        # the label tool, given its own text of language 2 twice, gives its own text of language 1: the fixed point
        c = run(a.out, st['A'], st['P'], checked=True, limit=LIMIT, stdin=twice(l2_text))
        self.assertEqual((c.rc, c.err.count('l2l:')), (0, 0), c.err)
        self.assertEqual(c.out, l1_text + b'\0')


