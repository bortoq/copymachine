PROGRAMS = os.path.join(common.HERE, 'programs')
LIMIT = 40 * 10 ** 6
SMALL = ['echo', 'branch', 'add16_hex', 'and_hex', 'arith8', 'arith16', 'array', 'loop_digits']      # the subset, small
STDIN = {'echo': b'hello, chain\0', 'arith8': b'\xa5\x3c', 'arith16': b'\x12\x34\x56\x78'}
TITLE = 'the image of %s.tw (A=%d, P=%d), generated by tower/l1text.py'
_TOOL = {}


def setUpModule():
    common.ensure_built()


def read(name, mode='r'):
    with open(os.path.join(PROGRAMS, name), mode, encoding=None if 'b' in mode else 'utf-8') as h:
        return h.read()


def compiled(name):
    p, errs = text.compile_text(read(name + '.tw'))
    assert not errs, errs
    return p


def tool():
    """The image of l3c.tw: serial layout, A = 20 (the Python compiler of the chain; part 3 replaces it)."""
    if not _TOOL:
        _TOOL.update(image=l3ctext.tool_image(), A=20, P=3)
    return _TOOL


def l3c(src, limit=LIMIT):
    """What the chain tool gives for a text of language 3 (bytes or str, the zero byte is added)."""
    t = tool()
    src = src.encode('latin-1') if isinstance(src, str) else src
    r = run(t['image'], t['A'], t['P'], checked=True, limit=limit, stdin=src + b'\0')
    assert r.ticks < limit, 'the tool ran out of ticks'
    return r


def hoisted(name):
    return l3ctext.hoist(read(name + '.tw'))


def image_of(l2):
    """The image of a text of language 2 with labels by the Python references of l2l and the seed."""
    l1, err = l2ltext.encode(l2[:-1] if l2.endswith(b'\0') else l2, twice=True)
    assert err is None, err
    img, err = l1text.encode(l1)
    assert err is None, err
    return img


class Reference(unittest.TestCase):
    """The texts and the Python reference (no emulator)."""

    def test_tables_are_current(self):
        """The numbers of the tables in l3c.tw are what l3ctext.tables_text makes."""
        src = read('l3c.tw')
        a, b = src.index('# --- begin generated\n'), src.index('# --- end generated')
        self.assertEqual(src[a + len('# --- begin generated\n'):b], l3ctext.tables_text())

    def test_tool_is_in_its_subset(self):
        """The text of l3c.tw is a text of the subset (the tool compiles itself, part 3): the reference takes it, it fits A = 20 with room, and
        its names (data, tables, arrays) are at most half of the places of l3c (1020), its labels (b and r) are fewer than the 1024 of l2l."""
        src = read('l3c.tw')
        out, err = l3ctext.encode(src)
        self.assertIsNone(err)
        c = l3ctext.Compiler()
        c.put(l3ctext.prelude())
        l3ctext.run(c, src.encode())
        self.assertLess(c.pos, l3ctext.LIMIT)
        self.assertGreater(len(c.syms), 255)
        self.assertLessEqual(2 * len(c.syms), l3ctext.MAXSYM)
        labels = len(re.findall(r'^:[brt]', ''.join(c.out), re.M)) + 1
        self.assertGreater(labels, 255)
        self.assertLess(labels, l2ltext.MAXLAB)

    def test_l3c_text_is_current(self):
        """programs/l3c.l1 (the seed of the tool: the text of language 1 that the seed turns into the image of l3c) is what the chain l3c -> l2l
        gives for l3c.tw (the reference: l3ctext.py -l); after a change of l3c.tw it is made again (see tower/README.md)."""
        l1, err = l3ctext.language1(read('l3c.tw').encode())
        self.assertIsNone(err)
        self.assertEqual(read('l3c.l1', 'rb'), l1)

    def test_capacity_in_the_texts(self):
        """The places of names: 1024 in l3c.tw (six arrays of 2^10, nsym over 11 bits), 1024 labels in l2l.tw and the references."""
        self.assertEqual((l3ctext.MAXSYM, l2ltext.MAXLAB), (1020, 1024))
        src = read('l3c.tw')
        for n in ('sna', 'snb', 'stg', 'ski', 'sad', 'sin'):
            self.assertIn(':%s array 10 ' % n, src)
        for n in ('nameh', 'namet', 'tags', 'vals', 'hd', 'nx'):
            self.assertIn(':%s array 10 ' % n, read('l2l.tw'))
        names = lambda n: ''.join(':a%d data 1 0\n' % i for i in range(n)) + ':main block\nhalt\n'   # noqa: E731
        self.assertIsNone(l3ctext.encode(names(1020))[1])
        self.assertEqual(l3ctext.encode(names(1021))[1], 'lab')
        lab = lambda n: ''.join(':n%d d 1 1\n' % i for i in range(n))   # noqa: E731
        self.assertIsNone(l2ltext.encode(lab(1024), twice=True)[1])
        self.assertEqual(l2ltext.encode(lab(1025), twice=True)[1], 'lab')

    def test_format(self):
        """The text of language 2 for the smallest program, and the layers of a copy (the layout is serial: a row and a jump)."""
        out, err = l3ctext.encode(':a data 8 5\n:main block\nhalt\n')
        self.assertIsNone(err)
        self.assertEqual(out.decode(), l3ctext.prelude() + 'd 8 5\n:bmain\nz 50\nc a0 0 &e\nz 7\n:e\n\0')
        out = l3ctext.encode(':a data 8 5\n:b data 8 0\n:main block\ncopy &b &a\nhalt\n')[0].decode()
        self.assertIn('d 8 5\nd 8 0\n:bmain\nc 8 e9 e1\nc a0 0 191\nz 50\nc a0 0 &e\n', out)

    def test_errors(self):
        """The classes of errors of the reference."""
        cases = {'bad': ['foo', ':a :b data 1 0', 'data 1 0', ':a data 0 1', ':a data 1 0 7', '&a', '"x', ':a data 8 5x', ':A\n', ':a\n'],
                 'lab': [':main block\ncopy &a &a\nhalt', ':a data 1 0\n:a data 1 0', ':zero data 1 0', ':add4 data 1 0',
                         ':a data 1 0\n:main block\nlut &a &a &a\nhalt'],
                 'wid': [':a data 8 0\n:b data 9 0\n:main block\ncopy &a &b\nhalt', ':a data 8 0\n:main block\ncopy &a[0:9] &a\nhalt',
                         ':a data 3 0\n:b data 3 0\n:main block\nadd &a &a &b\nhalt', ':a data 8 0\n:main block\nkey &a[0:4]\nhalt',
                         ':a data 8 "abc"', LONG + 'long! &p127 &o\nhalt', LONG + 'long@ &o &o\nhalt', LONG + 'long! &z &o\nhalt'],
                 'blk': [':main block\n:b block', ':main block\ngoto &main\nhalt', 'halt', ':main block\n:a data 1 0\nhalt',
                         ':main block\nret\nhalt', ':main block\nemit &zero', ':a block\n:b block'],
                 'big': [''.join(':a%d array 8 64\n' % i for i in range(40)), LONG + 'long! &p &w[0:%d]\nhalt' % (l3ctext.NMAX + 1)]}
        for why, texts in cases.items():
            for t in texts:
                self.assertEqual(l3ctext.encode(t)[1], why, t)

    def test_long_words(self):
        """Language 4 (23.17): the placeholder (the line `long`, a layer with the four numbers, ten layers of room), add4 used, the bits of the words."""
        src = LONG + 'long! &p &o\nlong@ &p &w[0:%d]\nhalt\n' % l3ctext.NMAX
        out, err = l3ctext.encode(src)
        self.assertIsNone(err)
        text = out.decode()
        self.assertEqual(text.count('long\n'), 2)
        self.assertTrue('long\nd 14 28\nd 14 %x\nd 14 %x\nd 14 ' % (l3ctext.START, l3ctext.START + 255) in text)      # n = 40, pos, the data
        self.assertTrue('long\nd 14 %x\n' % (l3ctext.NMAX | 1 << 19) in text)                                      # long@: bit 19
        self.assertTrue(':ta\n' in text)
        self.assertEqual(l3ctext.encode(LONG + 'halt\n')[0].count(b':ta'), 0)
        self.assertEqual(l3ctext.encode(src + 'copy &o &o\n')[1], 'blk')
        self.assertEqual((l3ctext.LONGL, l3ctext.QB + 204 + l3ctext.NMAX <= (1 << 20) - 6), (11, True))
        self.assertLess(l3ctext.QB, (1 << 20) - 6)
        a, b = (l3ctext.encode(LONG + '%s\nhalt\n' % w)[0].count(b'\nz 50\n') for w in ('copy &o &o', 'long! &p &o'))
        self.assertEqual(a, b)

    def test_cli(self):
        root = os.path.dirname(common.HERE)
        src = b':main block\nhalt\n'
        e = subprocess.run([sys.executable, '-B', 'tower/l3ctext.py', '-e'], input=src, cwd=root, check=False, capture_output=True,
                           timeout=120)
        self.assertEqual((e.returncode, e.stdout), (0, l3ctext.encode(src)[0]))
        e = subprocess.run([sys.executable, '-B', 'tower/l3ctext.py', '-t'], cwd=root, check=False, capture_output=True, timeout=120)
        self.assertEqual((e.returncode, e.stdout), (0, tool()['image']))
        e = subprocess.run([sys.executable, '-B', 'tower/l3ctext.py', '-e'], input=b'foo', cwd=root, check=False, capture_output=True,
                           timeout=120)
        self.assertEqual((e.returncode, e.stderr), (1, b'l3c: bad text\n'))


LONG = ':p data 128 0\n:p127 data 127 0\n:o data 40 "hello"\n:w data %d 0\n:z data 1 0\n:main block\n' % (l3ctext.NMAX + 1)


class Images(unittest.TestCase):
    """The images made from the reference output run as the images of the Python compiler (the layout is not the same, the output is)."""

    def test_programs(self):
        for name in SMALL:
            with self.subTest(name):
                out, err = l3ctext.encode(hoisted(name))
                self.assertIsNone(err)
                img = image_of(out)
                py = compiled(name)
                a = run(img, 20, 2, checked=True, limit=LIMIT, stdin=STDIN.get(name, b''))
                b = run(py.stats['image'], py.stats['A'], py.stats['P'], checked=True, limit=LIMIT, stdin=STDIN.get(name, b''))
                self.assertEqual((a.rc, b.rc), (0, 0), (a.err, b.err))
                self.assertEqual(a.out, b.out)
                self.assertTrue(a.out)

    def test_calls_and_stores(self):
        """A word with call and ret, an array written by store and read by lut, if, a string, shl and shr, lt eq band sub."""
        src = ''':msg data 24 "ab\\n"
:t table 2 4 5 6 7 8
:x array 3 4
:i data 3 0
:v data 4 0
:o data 4 0
:r data 3 0
:s data 5 0
:q data 1 0
:n data 8 0
:sh data 8 0
:h1 data 8 0
:h2 data 8 0
:main block
emit &msg[0:8]
copy &i[0:2] &msg[1:3]
call &w &m2
:m2 block
lt &o &v &r
eq &o &v &q
sub &o &v &s
shl &msg[0:8] &sh 3
shr &msg[0:8] &n 2
lut &hex4 &o &h1
lut &hex4 &s[0:4] &h2
emit &h1
emit &h2
if &q &m3 &m4
:m3 block
emit &msg[8:16]
halt
:m4 block
emit &msg[16:24]
halt
:w word
lut &t &i[0:2] &v
store &x &i &v
lut &x &i &o
ret
'''
        out, err = l3ctext.encode(src)
        self.assertIsNone(err, src)
        a = run(image_of(out), 20, 2, checked=True, limit=LIMIT)
        py, errs = text.compile_text(src)
        self.assertEqual(errs, [])
        b = run(py.stats['image'], py.stats['A'], py.stats['P'], checked=True, limit=LIMIT)
        self.assertEqual((a.rc, a.out), (0, b.out))
        self.assertEqual(a.out[:1], b'a')
        self.assertGreater(len(a.out), 3)


class Tool(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.t = tool()

    def check_text(self, src):
        """The chain and the Python reference agree on a text: the same bytes and the same report."""
        r = l3c(src)
        want, err = l3ctext.encode(src)
        self.assertEqual(r.out, want, src)
        self.assertEqual('l3c: ' in r.err, err is not None, (src, r.err))
        if err:
            self.assertIn(l3ctext.MESSAGES[err], r.err)
        else:
            self.assertEqual(r.rc, 0)
        return r

    def test_tool_image(self):
        self.assertEqual((self.t['A'], self.t['P']), (20, 3))
        self.assertLess(len(self.t['image']) * 8, 1 << 20)

    def test_programs(self):
        for name in SMALL:
            with self.subTest(name):
                self.check_text(hoisted(name))

    def test_data_tables_words(self):
        for src in (':main block\nhalt\n', ':a data 8 "ab"\n:t table 2 8 1 2 3 4\n:x array 3 5\n:w word\nret\n:main block\ncall &w &m2\n:m2 block\n'
                    'lut &t &a[0:2] &a[0:8]\nstore &x &a[0:3] &a[0:5]\nshl &a &a 3\nhalt\n',
                    ':a data 16 0\n:b data 17 0\n:c data 16 0\n:main block\nadd &a &c &b\nsub &a &c &b\nshr &a &c 4\nkey &a\nwarn &a\nhalt\n',
                    ':t table 2 24 "abc" "def" "ghi" "jkl"\n:main block\nhalt\n', ':a data 40 1048575\n:b data 21 0\n:main block\nhalt\n'):
            self.check_text(src)

    def test_long_words(self):
        """The words of language 4 and their errors: the same bytes and reports as the reference (the pass l4p is in test_l4p.py)."""
        for src in (LONG + 'long! &p &o\nlong@ &p &o\nhalt\n', LONG + 'long@ &p &w[0:117]\nlong! &p &w[0:%d]\nhalt\n' % l3ctext.NMAX,
                    LONG + 'long! &p127 &o\nhalt\n', LONG + 'long@ &o &o\nhalt\n', LONG + 'long! &p &w\nhalt\n', LONG + 'long! &p\nhalt\n',
                    LONG + 'long! &p &o &o\nhalt\n', LONG + 'long! 1 &o\nhalt\n', LONG + 'long!x &p &o\nhalt\n', LONG + 'long &p &o\nhalt\n',
                    LONG + 'long@@ &p &o\nhalt\n', ':a! data 1 0\n', ':a data 1 0\n:main block\ncopy &a! &a\nhalt\n', '!\n', '@long\n',
                    'long! &p &o\n', ':long! data 1 0\n', LONG + 'long!\n', 'pack\n' + LONG.replace(':main block\n', '') + ':main block\nlong@ &p &o\nhalt\n'):
            with self.subTest(src):
                self.check_text(src)

    def test_errors(self):
        for src in ('foo', ':a :b data 1 0', ':a data 1 0 7', ':a block\n:b block', '&a', '"x', ':a data 8 "abc" ', ':A\n', ':a data 8 5x',
                    ':main block\nret\nhalt', ':main block\ncopy &a &a\nhalt', ':a data 1 0\n:a data 1 0', ':zero data 1 0', ':add4 data 1 0',
                    ':a data 8 0\n:b data 9 0\n:main block\ncopy &a &b\nhalt', ':a data 8 0\n:main block\ncopy &a[0:9] &a\nhalt',
                    ':a data 3 0\n:main block\nadd &a &a &a\nhalt', ':a data 8 0\n:main block\nkey &a[0:4]\nhalt', ':a data 8 "abc"',
                    ':main block\n:b block', ':main block\ngoto &main\nhalt', 'halt', ':main block\n:a data 1 0\nhalt', ':a data 8 0\n:main block\nkey &a',
                    ':t table 1 8 "ab" "cd"', ':t table 1 16 "ab" "c"', ':t table 1 4 1', ':a data 8 "\\q"', ':a data 8 "' + 'x' * 33 + '"',
                    ':abcdefghijklmno data 1 0', ':a data 8 0\n:main block\nlut &add4 &a[0:4] &a[0:4] &a[0:1] &a[0:5]\nhalt',
                    ':a data 8 0\n:main block\nlut &hex4 &a[0:4]\nhalt', ':a data 1 0\n:b array 1 1\n:main block\nstore &b &a &a\nhalt',
                    ':a data 1 0\n:b table 1 1 0 1\n:main block\nstore &b &a &a\nhalt', ':a data 1 0\n:main block\nif &a &main\n'):
            self.check_text(src)

    def test_too_big_and_too_many(self):
        big = ''.join(':a%d array 8 64\n' % i for i in range(40)) + ':main block\nhalt\n'
        r = self.check_text(big)
        self.assertIn('too big', r.err)
        names = lambda n: ''.join(':a%d data 1 0\n' % i for i in range(n)) + ':main block\nhalt\n'   # noqa: E731
        self.assertEqual(self.check_text(names(300)).rc, 0)        # the old table had 251 places; 1020 and 1021 are in long_l3c.py

    def test_mutations(self):
        """Texts spoiled at random: the chain and the reference agree (a token dropped, replaced, doubled, the text cut)."""
        rng = random.Random(23)
        junk = ['&zz', '&a[', '&a[1:', '&a[3:2]', '"x', '1x', '0', '99999999', '&', 'block', 'data', 'halt', 'ret', ':', '::a', ':1a', '#',
                '&main', '&a[0]', '"\\n"', '&add4', '&hex4', 'zero', '&zero', 'data 8 0', 'table 1 1 5 6 7']
        bases = [hoisted(n) for n in ('echo', 'branch', 'and_hex')]
        for _ in range(40):
            toks = re.split(r'(\s+)', rng.choice(bases))
            for _ in range(rng.choice((1, 1, 2))):
                idx = [j for j in range(len(toks)) if toks[j].strip()]
                j, m = rng.choice(idx), rng.randrange(4)
                if m == 0:
                    toks[j] = rng.choice(junk)
                elif m == 1:
                    toks[j] = ''
                elif m == 2:
                    toks.insert(j, rng.choice(junk) + ' ')
                else:
                    toks = toks[:j]
                    break
            self.check_text(''.join(toks))


class Chain(unittest.TestCase):
    """The whole chain on the emulator: text of language 3 -> l3c -> l2l -> seed -> the image, which runs."""

    @classmethod
    def setUpClass(cls):
        cls.t = tool()
        cls.l2l = compiled('l2l').stats
        cls.seed = compiled('seed').stats

    def build(self, src):
        r = l3c(src)
        self.assertEqual(r.rc, 0, r.err)
        a = run(self.l2l['image'], self.l2l['A'], self.l2l['P'], checked=True, limit=LIMIT, stdin=r.out + r.out)
        self.assertEqual(a.rc, 0, a.err)
        b = run(self.seed['image'], self.seed['A'], self.seed['P'], checked=True, limit=LIMIT, stdin=a.out)
        self.assertEqual(b.rc, 0, b.err)
        self.assertEqual(b.out, image_of(r.out))
        return b.out

    def test_images(self):
        for name in ('echo', 'branch', 'loop_digits', 'and_hex'):
            with self.subTest(name):
                img = self.build(hoisted(name))
                py = compiled(name)
                a = run(img, 20, 2, checked=True, limit=LIMIT, stdin=STDIN.get(name, b''))
                b = run(py.stats['image'], py.stats['A'], py.stats['P'], checked=True, limit=LIMIT, stdin=STDIN.get(name, b''))
                self.assertEqual((a.rc, a.out), (0, b.out))
                self.assertTrue(a.out)


